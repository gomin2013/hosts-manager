#!/usr/bin/env node
// Regenerates Sources/HostsManagerApp/Resources/{en,th}.lproj/Localizable.strings from the i18n table in
// .prototype/javascripts/shared.js (the single source of truth) plus the HelperError messages below.
// Usage: node scripts/gen-strings.js   — then `swift test --filter LocalizationTests`
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const src = fs.readFileSync(path.join(root, ".prototype/javascripts/shared.js"), "utf8");
const i18n = new Function(src + "\nreturn i18n;")();

// HelperError.localizationKey — not shown by the prototype.
const helperErrors = {
  en: {
    "err.notInstalled": "The helper is not installed. Approve it in System Settings → General → Login Items.",
    "err.connectionFailed": "Could not connect to the helper. Approve it in System Settings → General → Login Items.",
    "err.staleFile": "/etc/hosts was changed by another app. Reloaded — please try again.",
    "err.invalidContent": "The helper rejected the file content.",
    "err.writeFailed": "Could not write /etc/hosts. Nothing was changed."
  },
  th: {
    "err.notInstalled": "ยังไม่ได้ติดตั้ง Helper กรุณาอนุญาตที่ System Settings → General → Login Items",
    "err.connectionFailed": "เชื่อมต่อ Helper ไม่ได้ กรุณาอนุญาตที่ System Settings → General → Login Items",
    "err.staleFile": "/etc/hosts ถูกแก้ไขโดยแอปอื่น โหลดใหม่แล้ว กรุณาลองอีกครั้ง",
    "err.invalidContent": "Helper ปฏิเสธเนื้อหาไฟล์",
    "err.writeFailed": "เขียน /etc/hosts ไม่สำเร็จ ไฟล์ไม่ถูกเปลี่ยนแปลง"
  }
};

for (const lang of ["en", "th"]) {
  const all = { ...i18n[lang], ...helperErrors[lang] };
  const body = Object.entries(all).map(([k, v]) => `"${k}" = "${v.replace(/"/g, '\\"')}";`).join("\n");
  const dir = path.join(root, `Sources/HostsManagerApp/Resources/${lang}.lproj`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "Localizable.strings"),
    `/* Hosts Manager — ${lang}. Generated by scripts/gen-strings.js from .prototype/javascripts/shared.js. */\n\n${body}\n`
  );
}
console.log("Localizable.strings regenerated (en, th)");
